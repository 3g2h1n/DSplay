#!/usr/bin/env python3
"""DSplay logo: a bold coral "D" whose counter is a cyan "play" triangle.

Writes
  source/logo_data.c / include/logo_data.h   RGB555 + alpha bitmaps for the console (30, 48 px)
  assets/icon.bmp                            32x32 16-colour banner icon of the .nds file
  studio/web/icon.svg                        Studio / browser icon
  assets/logo.png                            512 px picture (README, sharing)

    python3 tools/gen_logo.py      (needs Pillow)
"""
import os
import struct

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CORAL = (255, 96, 88)
CYAN = (0, 195, 227)
TILE = (250, 250, 250)


def _play(d, cx, cy, s, fill):
    """Play triangle of height s, centred on its visual centre, slightly rounded."""
    r = s * 0.10
    p = [(cx - s * 0.38, cy - s * 0.5), (cx - s * 0.38, cy + s * 0.5), (cx + s * 0.48, cy)]
    d.polygon(p, fill=fill)
    d.line(p + [p[0]], fill=fill, width=max(1, int(r * 2)), joint="curve")
    for x, y in p:
        d.ellipse([x - r, y - r, x + r, y + r], fill=fill)


def draw(size, scale=8):
    """RGBA logo of size x size pixels (transparent background)."""
    n = size * scale
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    m = n * 0.04                      # margin
    x0, y0, x1, y1 = m, m, n - m, n - m
    h = y1 - y0
    w = x1 - x0
    stem = w - h / 2                  # straight part, then a half circle
    rad = n * 0.10
    d.rounded_rectangle([x0, y0, x0 + stem + 1, y1], radius=rad, fill=CORAL + (255,))
    d.rectangle([x0 + stem * 0.5, y0, x0 + stem + 1, y1], fill=CORAL + (255,))
    d.pieslice([x1 - h, y0, x1, y1], -90, 90, fill=CORAL + (255,))
    # counter: a play triangle cut out of the D, a smaller cyan one inside it
    cx, cy = x0 + w * 0.47, (y0 + y1) / 2
    hole = Image.new("L", (n, n), 0)
    _play(ImageDraw.Draw(hole), cx, cy, h * 0.58, 255)
    from PIL import ImageChops
    img.putalpha(ImageChops.subtract(img.getchannel("A"), hole))
    _play(d, cx, cy, h * 0.36, CYAN + (255,))
    return img.resize((size, size), Image.LANCZOS)


def write_c(sizes):
    lines = ["// Generated by tools/gen_logo.py - DSplay logo (do not edit)", '#include "logo_data.h"', ""]
    hdr = ["// Generated by tools/gen_logo.py", "#ifndef LOGO_DATA_H", "#define LOGO_DATA_H", "#include <stdint.h>", "",
           "typedef struct { int size; const uint16_t *px; const uint8_t *alpha; } LogoBitmap;  // alpha 0..32", ""]
    for s in sizes:
        im = draw(s)
        px, al = [], []
        for r, g, b, a in im.getdata():
            px.append(0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10))
            al.append((a * 32 + 127) // 255)
        lines.append("static const uint16_t px%d[%d] = {" % (s, s * s))
        for i in range(0, len(px), 12):
            lines.append("    " + ", ".join("0x%04X" % v for v in px[i:i + 12]) + ",")
        lines.append("};")
        lines.append("static const uint8_t al%d[%d] = {" % (s, s * s))
        for i in range(0, len(al), 24):
            lines.append("    " + ", ".join(str(v) for v in al[i:i + 24]) + ",")
        lines.append("};")
        lines.append("const LogoBitmap g_logo%d = { %d, px%d, al%d };" % (s, s, s, s))
        lines.append("")
        hdr.append("extern const LogoBitmap g_logo%d;" % s)
    # "DSplay" wordmark (Inter Black): alpha only, "DS" and "play" are coloured at run time
    from PIL import ImageFont
    font = ImageFont.truetype("/usr/share/fonts/opentype/inter/Inter-Black.otf", 26 * 4)
    tmp = ImageDraw.Draw(Image.new("L", (1, 1)))
    w_ds = tmp.textlength("DS", font=font)
    wtot = tmp.textlength("DSplay", font=font)
    asc, desc = font.getmetrics()
    big = Image.new("L", (int(wtot) + 8, asc + desc), 0)
    ImageDraw.Draw(big).text((4, 0), "DSplay", font=font, fill=255)
    bbox = big.getbbox()
    big = big.crop((0, bbox[1], big.size[0], bbox[3]))
    W, H = (big.size[0] + 3) // 4, (big.size[1] + 3) // 4
    small = big.resize((W, H), Image.LANCZOS)
    split = int(round((4 + w_ds) / 4))
    al = [(v * 32 + 127) // 255 for v in small.getdata()]
    lines.append("static const uint8_t word_al[%d] = {" % (W * H))
    for i in range(0, len(al), 24):
        lines.append("    " + ", ".join(str(v) for v in al[i:i + 24]) + ",")
    lines.append("};")
    lines.append("const LogoWordmark g_wordmark = { %d, %d, %d, word_al };" % (W, H, split))
    hdr.insert(6, "typedef struct { int w, h, split; const uint8_t *alpha; } LogoWordmark;  // split: first column of \"play\"")
    hdr.append("extern const LogoWordmark g_wordmark;")
    hdr += ["", "#endif", ""]
    with open(os.path.join(ROOT, "source", "logo_data.c"), "w") as f:
        f.write("\n".join(lines))
    with open(os.path.join(ROOT, "include", "logo_data.h"), "w") as f:
        f.write("\n".join(hdr))


def write_bmp():
    """32x32, 4 bits per pixel: the logo on a white rounded tile (the DSi menu icon)."""
    n = 32
    big = Image.new("RGBA", (n * 8, n * 8), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle([0, 0, n * 8 - 1, n * 8 - 1], radius=n * 8 * 0.22, fill=TILE + (255,))
    big = big.resize((n, n), Image.LANCZOS)
    logo = draw(24)
    big.alpha_composite(logo, (4, 4))
    bg = Image.new("RGB", (n, n), (255, 0, 255))      # colour 0 = transparent on the DSi
    alpha = big.getchannel("A").point(lambda v: 255 if v > 100 else 0)
    bg.paste(big.convert("RGB"), (0, 0), alpha)
    # fixed palette: the logo colours and their blends with the white tile (no dithering)
    def mix(a, b, t):
        return tuple(int(a[i] * (1 - t) + b[i] * t) for i in range(3))
    cols = [(255, 0, 255), TILE, CORAL, CYAN]
    for t in (0.25, 0.5, 0.75):
        cols += [mix(CORAL, TILE, t), mix(CYAN, TILE, t)]
    cols += [mix(CORAL, CYAN, 0.5), (200, 200, 200), (230, 230, 230), (120, 120, 120), (40, 40, 40), (90, 160, 180)]
    palimg = Image.new("P", (1, 1))
    palimg.putpalette(sum((list(c) for c in cols[:16]), []) + [0] * (768 - 48))
    q = bg.quantize(palette=palimg, dither=Image.Dither.NONE)
    pal = q.getpalette()[:48]
    # palette index of the transparent colour goes first
    idx = list(q.getdata())
    key = min(range(16), key=lambda i: abs(pal[i * 3] - 255) + pal[i * 3 + 1] + abs(pal[i * 3 + 2] - 255))
    order = [key] + [i for i in range(16) if i != key]
    remap = {old: new for new, old in enumerate(order)}
    pal2 = sum(([pal[o * 3 + 2], pal[o * 3 + 1], pal[o * 3], 0] for o in order), [])
    rows = []
    for y in range(n - 1, -1, -1):   # bottom-up
        row = bytearray()
        for x in range(0, n, 2):
            row.append((remap[idx[y * n + x]] << 4) | remap[idx[y * n + x + 1]])
        rows.append(bytes(row))
    data = b"".join(rows)
    off = 14 + 40 + 64
    with open(os.path.join(ROOT, "assets", "icon.bmp"), "wb") as f:
        f.write(b"BM" + struct.pack("<IHHI", off + len(data), 0, 0, off))
        f.write(struct.pack("<IiiHHIIiiII", 40, n, n, 1, 4, 0, len(data), 2835, 2835, 16, 16))
        f.write(bytes(pal2))
        f.write(data)


SVG = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <defs><mask id="m"><rect width="64" height="64" fill="#fff"/>
    <path d="M24.5 19.4 L24.5 44.6 L45.7 32 Z" fill="#000" stroke="#000" stroke-width="3.6" stroke-linejoin="round"/></mask></defs>
  <rect x="2" y="2" width="60" height="60" rx="14" fill="#fafafa"/>
  <path d="M10 13 Q10 9 14 9 L32 9 A23 23 0 0 1 32 55 L14 55 Q10 55 10 51 Z" fill="#ff6058" mask="url(#m)"/>
  <path d="M27.4 24.4 L27.4 39.6 L40.2 32 Z" fill="#00c3e3" stroke="#00c3e3" stroke-width="2.2" stroke-linejoin="round"/>
</svg>
"""


def main():
    write_c([30, 48])
    write_bmp()
    with open(os.path.join(ROOT, "studio", "web", "icon.svg"), "w") as f:
        f.write(SVG)
    big = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle([0, 0, 511, 511], radius=112, fill=TILE + (255,))
    big.alpha_composite(draw(420), (46, 46))
    big.save(os.path.join(ROOT, "assets", "logo.png"))
    print("logo written")


if __name__ == "__main__":
    main()
