#!/usr/bin/env python3
"""
DSplay - anti-aliased font atlas generator.

Renders the Inter typeface (SIL Open Font License 1.1) into 4-bit alpha glyph
bitmaps and writes them as C source (source/font_data.c + include/font_data.h).
The generated files are committed, so this script is only needed if you want
to change sizes or the character set.

Usage:  python3 tools/gen_font.py [path/to/inter/otf/dir]
Requires Pillow (pip install pillow).
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"

# id, file, pixel size
FONTS = [
    ("FONT_SMALL", "Inter-Medium.otf", 9),
    ("FONT_BODY", "Inter-Medium.otf", 11),
    ("FONT_BOLD", "Inter-SemiBold.otf", 12),
    ("FONT_TITLE", "Inter-SemiBold.otf", 15),
    ("FONT_HUGE", "Inter-Medium.otf", 22),
]

CHARS = [chr(c) for c in range(32, 127)]
CHARS += list("ÇçĞğİıÖöŞşÜüÂâÎîÛûÁáÀàÄäÃãÉéÈèÊêËëÍíÌìÏïÓóÒòÔôÕõÚúÙùÑñßŒœƏə")
CHARS += list("•…←→↑↓°©★✓×·–—’‘“”¿¡€")
# Symbol pack for profile names (typed with the keyboard's symbol page or from Studio).
# Glyphs that Inter lacks come from the fallback fonts below.
SYMBOLS = ("★☆✦✧✩✪✫✬✭✮✯✰⋆♥♡❤❥❣✿❀❁✾❃❋✽❖♪♫♬♩☺☻☹☼☀☁☂☃☾☽⚡☯☮♛♚♕♔♠♣♦♢♤♧⚔☠✌✈☕⚽"
           "✓✔✗✘➜➤⇒‹›«»∞≈≠±÷√πΩµ∆▲▼◆◇○●◎□■△▽◀▶ツ『』「」【】《》〖〗༺༻꧁꧂")
CHARS += list(SYMBOLS)
CHARS = sorted(set(CHARS), key=ord)

FONTS_DIR_LOCAL = os.path.join(HERE, "fonts")
# fallback fonts: (regular, bold)
FALLBACKS = [
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    ("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc", "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"),
    (os.path.join(FONTS_DIR_LOCAL, "NotoSerifTibetan-Regular.ttf"), os.path.join(FONTS_DIR_LOCAL, "NotoSerifTibetan-Regular.ttf")),
    (os.path.join(FONTS_DIR_LOCAL, "NotoSansJavanese-Regular.ttf"), os.path.join(FONTS_DIR_LOCAL, "NotoSansJavanese-Bold.ttf")),
]


def _cmap(path):
    from fontTools.ttLib import TTFont
    try:
        return set(TTFont(path, fontNumber=0).getBestCmap().keys())
    except Exception:
        return set()


def render_font(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    bold = "Bold" in path or "SemiBold" in path
    chain = [(font, _cmap(path), 0)]
    for reg, bld in FALLBACKS:
        fp = bld if bold else reg
        if not os.path.isfile(fp):
            continue
        ff = ImageFont.truetype(fp, size)
        fa, _ = ff.getmetrics()
        chain.append((ff, _cmap(fp), ascent - fa))   # keep the baselines aligned
    glyphs = []
    for ch in CHARS:
        src = next(((f, dy) for f, cm, dy in chain if ord(ch) in cm or ch == " "), None)
        if src is None:
            print("  no font has", repr(ch))
            continue
        f, dy = src
        try:
            mask = f.getmask(ch, mode="L")
        except Exception:
            continue
        bbox = f.getbbox(ch)  # relative to origin at top (ascender line)
        adv = f.getlength(ch)
        w, h = mask.size
        img = Image.new("L", (w, h))
        if w and h:
            img.putdata(list(mask))
        x0 = bbox[0] if w else 0
        y0 = (bbox[1] if h else 0) + dy
        glyphs.append((ord(ch), w, h, x0, y0, int(round(adv)), img))
    return ascent, descent, glyphs


def pack4(img):
    w, h = img.size
    data = list(img.getdata())
    out = bytearray()
    for y in range(h):
        row = data[y * w:(y + 1) * w]
        if w % 2:
            row = row + [0]
        for i in range(0, len(row), 2):
            a = (row[i] * 15 + 127) // 255
            b = (row[i + 1] * 15 + 127) // 255
            out.append(a | (b << 4))
    return out


def main():
    c_lines = ['// Generated by tools/gen_font.py - do not edit by hand.',
               '// Typeface: Inter (c) The Inter Project Authors, SIL Open Font License 1.1',
               '// Symbols: DejaVu Sans (Bitstream Vera license), Noto Sans CJK / Noto Serif Tibetan / Noto Sans Javanese (SIL OFL 1.1)',
               '#include "font_data.h"', '']
    h_lines = ['// Generated by tools/gen_font.py - do not edit by hand.',
               '#ifndef FONT_DATA_H', '#define FONT_DATA_H', '#include <stdint.h>', '',
               'typedef struct {', '    uint16_t code;', '    uint8_t w, h;', '    int8_t xoff, yoff;',
               '    uint8_t adv;', '    uint8_t _pad;', '    uint32_t offset;', '} FontGlyph;', '',
               'typedef struct {', '    const FontGlyph *glyphs;', '    const uint8_t *bitmap;',
               '    uint16_t count;', '    uint8_t ascent, descent, line_h;', '} FontData;', '',
               'typedef enum {']
    for i, (fid, _, _) in enumerate(FONTS):
        h_lines.append(f'    {fid} = {i},')
    h_lines += ['    FONT_COUNT', '} FontId;', '', 'extern const FontData g_fonts[FONT_COUNT];', '', '#endif', '']

    table = []
    for fid, fname, size in FONTS:
        ascent, descent, glyphs = render_font(os.path.join(FONT_DIR, fname), size)
        name = fid.lower()
        bitmap = bytearray()
        entries = []
        for code, w, h, x0, y0, adv, img in glyphs:
            off = len(bitmap)
            bitmap += pack4(img)
            entries.append(f'    {{0x{code:04X}, {w}, {h}, {x0}, {y0}, {adv}, 0, {off}}},')
        c_lines.append(f'static const FontGlyph {name}_glyphs[{len(entries)}] = {{')
        c_lines += entries
        c_lines.append('};')
        c_lines.append(f'static const uint8_t {name}_bitmap[{len(bitmap)}] = {{')
        for i in range(0, len(bitmap), 24):
            c_lines.append('    ' + ','.join(str(b) for b in bitmap[i:i + 24]) + ',')
        c_lines.append('};')
        c_lines.append('')
        line_h = ascent + descent
        table.append(f'    {{{name}_glyphs, {name}_bitmap, {len(entries)}, {ascent}, {descent}, {line_h}}},')
        print(f"{fid}: {len(entries)} glyphs, {len(bitmap)} bytes, ascent={ascent} descent={descent}")
    c_lines.append('const FontData g_fonts[FONT_COUNT] = {')
    c_lines += table
    c_lines.append('};')
    c_lines.append('')

    with open(os.path.join(ROOT, "source", "font_data.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(c_lines))
    with open(os.path.join(ROOT, "include", "font_data.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(h_lines))


if __name__ == "__main__":
    main()
